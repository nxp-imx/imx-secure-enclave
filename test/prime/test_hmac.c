static int32_t complete_hmac_ops(prime_hdl_t service_hdl,
				 crypto_op_args_t **ops,
				 uint32_t nb_ops)
{
	uint32_t i;

	for (i = 0; i < nb_ops; i++) {
		data_cache_clean(ops[i]->op_mac_args.digest.virt_addr,
				 ops[i]->op_mac_args.digest.len, CACHE_CLEAN_INVALIDATE);

		if (prime_mcompare(ops[i]->op_mac_args.digest.virt_addr,
				   digest, ops[i]->op_mac_args.digest.len)) {
			printf("SHA2-256-HMAC test failed\n");
			return -1;
		} else {
			return 0;
		}
	}
}

static void prepare_hmac_op(prime_hdl_t service_hdl,
			    crypto_op_args_t *op,
			    hmac_key_t *key_args,
			    int dir,
			    void *va,
			    uint64_t phys)
{
	op->src.len = sizeof(msg);
	op->src.virt_addr = (uint8_t *)va;
	op->src.phys_addr = phys;

	/* copy the test vector & cache clean */
	prime_mcopy(op->src.virt_addr, msg, op->src.len);
	data_cache_clean(op->src.virt_addr, op->src.len, CACHE_CLEAN_ONLY);

	/* allocate digest buffer from reserved memory  */
	op->op_mac_args.digest.len = 32;

	op->op_mac_args.digest.virt_addr = op->src.virt_addr + op->src.len;
	op->op_mac_args.digest.phys_addr = op->src.phys_addr + op->src.len;

	/* prepare op */
	op->op_type = CRYPTO_OP_TYPE_HMAC;
	op->op_mac_args.sha_algo = key_args->sha_algo;
	op->op_mac_args.keyslot = key_args->keyslot;
	op->op_mac_args.dir = dir;		// dir = {0:generate, 1:verify}
	op->crypto_status.phys_addr = (status_buf_t *)(op->op_mac_args.digest.phys_addr +
				      ALIGN_UP(op->op_mac_args.digest.len, 64));
	op->crypto_status.virt_addr = (status_buf_t *)(op->op_mac_args.digest.virt_addr +
				      ALIGN_UP(op->op_mac_args.digest.len, 64));
}

int hmac_load_key(prime_hdl_t service_hdl, hmac_key_t *key_args, int sha_algo)
{
	key_args->key = hmac_key;
	key_args->keylen = sizeof(hmac_key);
	key_args->sha_algo = sha_algo;

	return prime_mac_init(service_hdl, key_args);
}

int hmac_test(prime_hdl_t service_hdl, void *va, uint64_t phys)
{
	hmac_key_t key_args = {0};
	crypto_op_args_t op = {0};
	crypto_op_args_t *op_ptr;
	uint32_t nb_ops;
	int32_t err;

	/* load hmac key */
	err = hmac_load_key(service_hdl, &key_args, CRYPTO_AUTH_SHA_256);
	if (err)
		return err;

	/* prepare op */
	prepare_hmac_op(service_hdl, &op, &key_args, CRYPTO_AUTH_OP_HMAC_GEN, va, phys);

	/* fill ops array */
	op_ptr = &op;
	nb_ops = 1;

	/* invoke fast crypto engine */
	err = prime_process_ops(service_hdl, &op_ptr, nb_ops);
	if (err)
		return err;

	/* complete execution and free memory */
	err = complete_hmac_ops(service_hdl, &op_ptr, nb_ops);

	return err;
}

int test_hmac_keyslot(prime_hdl_t service_hdl)
{
	hmac_key_t key_args = {0};
	int32_t err;
	uint8_t max_keyslot = MAX_PRIME_KEY_SLOT_SUPPORTED;

	/* load hmac key */
	while (max_keyslot) {
		err = hmac_load_key(service_hdl, &key_args, CRYPTO_AUTH_SHA_256);
		if (err && max_keyslot)
			return err;

		max_keyslot--;
	}
	return 0;
}
